// Patterns RE2 cannot express. Each maps to a Go predicate implemented by hand;
// the generator refuses to emit a pattern that is neither RE2-valid nor listed here.
const PREDICATES = {
  '^[\\p{Emoji_Presentation}\\p{Extended_Pictographic}]': 'pictographic',
}

// Translates a JS regex source into Go regexp syntax.
//
// Only the escape spelling changes: \uXXXX becomes \x{XXXX}, which is the same
// codepoint. Backslash runs are walked pairwise so an escaped backslash stays an
// escaped backslash — compromise's 'un-vite' rule is `\\-`, a literal backslash
// followed by a hyphen, and collapsing it to `\-` would make the rule fire on
// ordinary hyphenated words the TS oracle never tagged.
const goPattern = function (src, flags) {
  let out = ''
  for (let i = 0; i < src.length; ) {
    const ch = src[i]
    if (ch === '\\') {
      const next = src[i + 1]
      if (next === 'u' && /^[0-9a-fA-F]{4}$/.test(src.slice(i + 2, i + 6))) {
        out += '\\x{' + src.slice(i + 2, i + 6).toLowerCase() + '}'
        i += 6
        continue
      }
      // any other escape, including \\, is copied as a unit so its meaning holds
      out += ch + (next === undefined ? '' : next)
      i += next === undefined ? 1 : 2
      continue
    }
    const cp = ch.codePointAt(0)
    if (cp > 0x7e) {
      out += '\\x{' + cp.toString(16) + '}'
      i += ch.length
      continue
    }
    out += ch
    i += 1
  }
  return flags && flags.includes('i') ? '(?i)' + out : out
}

const re2Failures = []
const emittedPatterns = []

// Verifies a pattern against Go's regexp at generation time. Node cannot run Go's
// parser, so this approximates it by rejecting the constructs RE2 lacks.
const checkRE2 = function (pattern, where) {
  const unsupported = [
    [/\(\?[=!]/, 'lookahead'],
    [/\(\?<[=!]/, 'lookbehind'],
    [/\\[1-9]/, 'backreference'],
    [/\\p\{Emoji_Presentation\}/, '\\p{Emoji_Presentation}'],
    [/\\p\{Extended_Pictographic\}/, '\\p{Extended_Pictographic}'],
  ]
  for (const [re, why] of unsupported) {
    if (re.test(pattern)) {
      re2Failures.push({ pattern, where, why })
      return false
    }
  }
  emittedPatterns.push({ pattern, where })
  return true
}

const tagsOf = tag => (tag === undefined || tag === null ? [] : Array.isArray(tag) ? tag : [tag])

const emitRegexRule = function (r) {
  const parts = []
  const pattern = goPattern(r.regex, r.flags)
  if (PREDICATES[r.regex] !== undefined) {
    parts.push(`predicate: ${q(PREDICATES[r.regex])}`)
  } else {
    checkRE2(pattern, `regexRule ${r.reason || r.regex}`)
    parts.push(`pattern: ${q(pattern)}`)
  }
  parts.push(`tags: []string{${strSlice(tagsOf(r.tag))}}`)
  parts.push(`reason: ${q(r.reason || '')}`)
  return `{${parts.join(', ')}}`
}

// Emits a Go string literal. Every non-ASCII rune is escaped, because Go's parser
// rejects a literal U+FEFF anywhere but the first bytes of a file, and the model
// data carries zero-width joiners and other invisibles that must survive verbatim.
const q = function (s) {
  let out = '"'
  for (const ch of String(s)) {
    const cp = ch.codePointAt(0)
    if (ch === '"') out += '\\"'
    else if (ch === '\\') out += '\\\\'
    else if (ch === '\n') out += '\\n'
    else if (ch === '\t') out += '\\t'
    else if (ch === '\r') out += '\\r'
    else if (cp < 0x20 || cp === 0x7f) out += '\\x' + cp.toString(16).padStart(2, '0')
    else if (cp < 0x7f) out += ch
    else if (cp <= 0xffff) out += '\\u' + cp.toString(16).padStart(4, '0')
    else out += '\\U' + cp.toString(16).padStart(8, '0')
  }
  return out + '"'
}

// A null clue value is falsy in compromise, so the lookup falls through to the
// next clue source. Emitting it as the string "null" would instead make it a
// winning tag named 'null'.
const strMap = obj => {
  const keys = Object.keys(obj)
    .filter(k => obj[k] !== null && obj[k] !== undefined)
    .sort()
  return keys.map(k => `\t${q(k)}: ${q(String(obj[k]))},`).join('\n')
}

const boolSet = obj => {
  const keys = Object.keys(obj)
    .filter(k => obj[k] === true)
    .sort()
  return keys.map(k => `\t${q(k)}: {},`).join('\n')
}

const strSlice = arr => arr.map(q).join(', ')

// --- lexicon.gen.go ---
{
  // lexicon values are either a tag string or an array of tags
  const single = {}
  const multi = {}
  for (const [word, tag] of Object.entries(lexicon)) {
    if (Array.isArray(tag)) multi[word] = tag
    else single[word] = tag
  }
  const lines = [header]
  lines.push(`// lexicon holds ${Object.keys(lexicon).length} word->tag entries.`)
  lines.push(`var lexicon = map[string]string{`)
  lines.push(strMap(single))
  lines.push(`}\n`)
  lines.push(`var lexiconMulti = map[string][]string{`)
  for (const k of Object.keys(multi).sort()) {
    lines.push(`\t${q(k)}: {${strSlice(multi[k])}},`)
  }
  lines.push(`}\n`)
  lines.push(`var multiCache = map[string]int{`)
  for (const k of Object.keys(misc.multiCache).sort()) {
    lines.push(`\t${q(k)}: ${misc.multiCache[k]},`)
  }
  lines.push(`}\n`)
  lines.push(`var frozenLex = map[string]string{`)
  lines.push(strMap(misc.frozenLex))
  lines.push(`}\n`)
  writeFileSync(new URL('lexicon.gen.go', OUT), lines.join('\n'))
}

